namespace Endfix.Telegram.BotAPI.Enums;

/// <summary>Identifies a Telegram chat background variant.</summary>
public enum BackgroundTypes
{
    /// <summary>A background generated from a fill.</summary>
    Fill,

    /// <summary>A wallpaper image background.</summary>
    Wallpaper,

    /// <summary>A pattern applied over a fill.</summary>
    Pattern,

    /// <summary>A background based on a chat theme.</summary>
    ChatTheme
}
